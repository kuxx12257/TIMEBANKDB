ALTER SESSION SET CONTAINER = FREEPDB1;
SET SERVEROUTPUT ON
WHENEVER SQLERROR CONTINUE
SPOOL ..\logs\00_create_user.log
SHOW CON_NAME
ACCEPT TIMEBANK_PASSWORD CHAR PROMPT 'Enter password for TIMEBANK: ' HIDE
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM dba_users WHERE username = 'TIMEBANK';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE USER timebank IDENTIFIED BY &TIMEBANK_PASSWORD';
    DBMS_OUTPUT.PUT_LINE('User TIMEBANK created.');
  ELSE
    DBMS_OUTPUT.PUT_LINE('User TIMEBANK already exists - reusing it.');
  END IF;
END;
/
GRANT CONNECT, RESOURCE TO timebank;
GRANT CREATE VIEW, CREATE PROCEDURE, CREATE TRIGGER, CREATE SEQUENCE TO timebank;
ALTER USER timebank QUOTA UNLIMITED ON USERS;
PROMPT
PROMPT ===> Done. You can close this window and run 1_BUILD_DATABASE.bat
SPOOL OFF
EXIT
